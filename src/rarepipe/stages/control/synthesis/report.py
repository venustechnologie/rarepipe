"""Render a synthesis report as an architecture map a scientist can read. Generated, never edited."""
from __future__ import annotations

from rarepipe.stages.control.synthesis.compiler import SynthesisReport
from rarepipe.stages.control.synthesis.kinds import LogicalStatus, PhysicalStatus

SPECIFICATION = (
    "Do not ask biology only what will happen if we perturb it. Ask what biology must do for the "
    "desired state to exist, then synthesize a way to make those conditions true."
)


def _route(composition) -> str:
    return " → ".join(" + ".join(step) for step in composition)


def _variant(vid: str) -> str:
    return vid.split("::", 1)[-1]


def _short(name: str) -> str:
    return name.removeprefix("BB_")


def render(report: SynthesisReport) -> str:
    L: list[str] = []
    w = L.append
    w(f"# Architecture map — {report.case_ref}")
    w("")
    w("> **Reason with agents. Prove with code.** Every verdict below was computed by the "
      "deterministic compiler. This is a simulated analysis of a state-control problem: not a "
      "finding about the patient, not a claim that anything here can be built, and not a "
      "treatment recommendation.")
    w("")
    w(f"> {SPECIFICATION}")
    w("")
    w(f"Generated by `{report.synthesis_compiler_version}` on `{report.control_compiler_version}` · "
      f"synthesis model `{report.synthesis_model_version}` · state model "
      f"`{report.state_model_version}` · rules `{report.rule_version}` · digest "
      f"`{report.content_digest}`")
    w("")

    w(f"## Result: `{report.result.value}`")
    w("")
    w(report.result_meaning[0].upper() + report.result_meaning[1:] + ".")
    if report.abstention_reason:
        w("")
        w(f"**Why not more than that.** {report.abstention_reason[0].upper()}"
          f"{report.abstention_reason[1:]}.")
    if report.secondary_results:
        w("")
        w("Also true of this compilation: "
          + ", ".join(f"`{r.value}`" for r in report.secondary_results) + ".")
    w("")
    w(f"**Target accountability:** `{report.target_accountability}`. "
      + ("No accountable scientist has approved what counts as success here, so every verdict "
         "below is conditional on a target definition that is still a proposal."
         if report.target_accountability != "APPROVED" else
         "The target has been approved by an accountable human."))
    w("")
    w(f"**{report.logical_vs_physical}**")
    w("")
    w(f"**Scale of what was reached.** {report.rescue_scope_statement[0].upper()}"
      f"{report.rescue_scope_statement[1:]}.")
    w("")

    # ---------------------------------------------------------------- the inversion
    w("## What must become true")
    w("")
    w("The target region, decomposed. Nothing here names an intervention: the entry points are "
      "positions in the causal model where a mechanism would have to act.")
    w("")
    w("| Must hold | Currently | Already met | Scale | Entry points | Depends on resolving |")
    w("|---|---|---|---|---|---|")
    for r in report.required_functions.required:
        w(f"| `{r.variable}` ∈ {{{', '.join(r.must_enter)}}} | {', '.join(r.currently) or '—'} | "
          f"{'yes' if r.already_satisfied else 'no'} | {r.scale.value} | "
          f"{', '.join(f'`{e}`' for e in r.entry_points) or '—'} | "
          f"{', '.join(f'`{d}`' for d in r.unresolved_dependencies) or '—'} |")
    w("")
    if report.entry_points:
        w(f"**Entry points across every unmet requirement:** "
          + ", ".join(f"`{e}`" for e in report.entry_points) + ".")
        w("")

    # ---------------------------------------------------------------- architectures
    w("## Architectures")
    w("")
    if not report.architectures:
        w("No composition of the registered building blocks reached the target. That is a "
          "statement about this registry and this model, not about biology.")
        w("")
    else:
        w("| Architecture | Reaches the target | Can it be built | Across models | Holds? |")
        w("|---|---|---|---|---|")
        for a in report.architectures:
            built = ("**yes**" if a.physical is PhysicalStatus.PHYSICALLY_FEASIBLE
                     else "unknown" if a.physical is PhysicalStatus.SYNTHETIC_ROUTE_FEASIBILITY_UNKNOWN
                     else "no")
            w(f"| `{_route(a.composition)}`"
              + (" *(closed loop)*" if a.feedback_policy else "")
              + f" | {a.logical.value} | {built} | {a.robustness.value} | {a.stability.value} |")
        w("")
        for a in report.architectures:
            w(f"### `{_route(a.composition)}`"
              + (" — closed loop" if a.feedback_policy else ""))
            w("")
            w(f"- **Family:** {a.family} · **origin:** {a.origin.value} · **composition:** "
              f"{a.composition_mode.value} · **scale:** "
              f"{', '.join(s.value for s in a.scales)}")
            w(f"- **Reaches the target:** `{a.logical.value}`"
              + (f" — under {', '.join(_variant(v) for v in a.works_in)}" if a.works_in else "")
              + (f"; fails under {', '.join(_variant(v) for v in a.fails_in)}" if a.fails_in else ""))
            w(f"- **Can it be built:** `{a.physical.value}`"
              + (f" — nothing is established for {', '.join(f'`{b}`' for b in a.feasibility_blockers)}"
                 if a.feasibility_blockers else ""))
            w(f"- **Across competing models:** {', '.join(f'{m}={v}' for m, v in a.per_model)}")
            w(f"- **Durability:** `{a.stability.value}` — {a.stability_note}")
            w(f"- **What a reached target would mean:** {a.rescue_scope}")
            if a.overrides_relationships:
                w(f"- **Overrides:** {', '.join(f'`{o}`' for o in a.overrides_relationships)} — "
                  "each overridden relationship is a function this architecture assumes some "
                  "mechanism supplies, which is a requirement of its own")
            if a.blocking_relationships:
                w(f"- **Blocked by:** {', '.join(f'`{b}`' for b in a.blocking_relationships)}")
            if a.irrelevant_unknowns:
                w(f"- **Unknowns that do not affect this route:** "
                  f"{', '.join(f'`{u}`' for u in a.irrelevant_unknowns)}")
            if a.unresolved_relied_on:
                w(f"- **Leans on unresolved links:** "
                  f"{', '.join(f'`{u}`' for u in a.unresolved_relied_on)}")
            if a.unsafe_in:
                violated = a.unsafe_path[-1] if a.unsafe_path else {}
                w(f"- **Rejected on safety** under {', '.join(_variant(v) for v in a.unsafe_in)}. "
                  "The trajectory enters a forbidden state; no benefit is weighed against it."
                  + (f" Final state: " + ", ".join(f"`{k}`={v}" for k, v in sorted(violated.items())
                                                   if k in {'cell_death', 'viability',
                                                            'division_rate', 'toxicity'})
                     if violated else ""))
            if a.order_note:
                w(f"- **Order:** {a.order_note}")
            if a.feedback_status:
                w(f"- **Loop:** {a.feedback_status}")
            if a.unobservable_policy_inputs:
                w(f"- **Policy reads what nobody measures:** "
                  f"{', '.join(f'`{v}`' for v in a.unobservable_policy_inputs)}")
            if a.missing_release_declarations:
                w(f"- **Release undeclared for:** "
                  f"{', '.join(f'`{c}`' for c in a.missing_release_declarations)}")
            if a.undeclared_population_mechanisms:
                w(f"- **Population change with no stated differential:** "
                  f"{', '.join(f'`{v}`' for v in a.undeclared_population_mechanisms)}")
            if a.confounder_gaps:
                for gap in a.confounder_gaps:
                    w(f"- **Confounded reading:** {gap.consequence}")
            if a.assumptions:
                w("- **Assumptions it rests on:**")
                for item in a.assumptions:
                    w(f"    - {item}")
            w("")

    # ---------------------------------------------------------------- families
    if report.families:
        w("## Families the compiler was asked to consider")
        w("")
        w("Each family was asked about whether or not anything implements it, so that a family "
          "nobody has a mechanism for is distinguishable from one that was never considered.")
        w("")
        w("| Family | Verdict | Why |")
        w("|---|---|---|")
        for f in report.families:
            w(f"| **{f.family_id}** — {f.description} | `{f.verdict.value}` | {f.reason} |")
        w("")

    # ---------------------------------------------------------------- experiments
    if report.experiment_discriminators:
        w("## What would eliminate the most architectures")
        w("")
        w(f"Criterion: `{report.experiment_criterion}`. {report.experiment_criterion_note}")
        w("")
        w("| Measure | While holding | Resolves | Reading | Contrary reading | Rules out | "
          "Measured by |")
        w("|---|---|---|---|---|---|---|")
        for d in report.experiment_discriminators:
            w(f"| `{d.measurement}` | "
              f"{', '.join(_short(c.split('::')[0]) for c in d.controls_held) or '—'} | "
              f"`{d.resolves}` | {', '.join(d.reading)} | {', '.join(d.contrary_reading) or '—'} | "
              f"{d.at_most_eliminated} | "
              f"{', '.join(d.observed_by) if d.observed_by else '**nothing measures it**'} |")
        w("")
        unmeasurable = [d for d in report.experiment_discriminators if not d.measurable]
        if unmeasurable:
            w(f"{len(unmeasurable)} of these would settle a question that no existing experiment "
              "can read. That is a gap in the measurement set, not an experiment anybody can run:")
            for d in unmeasurable:
                w(f"- `{d.measurement}` — {d.note}")
            w("")
        for d in report.experiment_discriminators:
            if d.valid_only_with:
                w(f"- `{d.measurement}` is valid only alongside "
                  f"{', '.join(f'`{v}`' for v in d.valid_only_with)}: without it the reading "
                  "could be produced by something the model omits.")
        w("")

    if report.confounder_gaps:
        w("## Readings that cannot be trusted yet")
        w("")
        for gap in report.confounder_gaps:
            w(f"- **`{gap.variable}`** — {gap.consequence}")
        w("")

    # ---------------------------------------------------------------- components
    w("## Building blocks")
    w("")
    w("What each piece is declared to *do*, not what it is called. A component is stored as a "
      "transformation of state, so the compiler can compose pieces without consulting any "
      "therapeutic indication.")
    w("")
    w("| Component | Class | Transformations | Scale | Can it be built | Why not |")
    w("|---|---|---|---|---|---|")
    for b in report.building_blocks:
        w(f"| `{b['building_block']}` | {b['class']} | {'; '.join(b['transformations'])} | "
          f"{', '.join(b['scale'])} | {b['feasibility']} | {b['feasibility_note']} |")
    w("")
    for b in report.building_blocks:
        w(f"- **`{b['building_block']}`** — {b['mechanism']}. *Evidence:* {b['evidence']}. "
          f"*Uncertainty:* {b['uncertainty']}. *Epistemic type:* `{b['epistemic_type']}`.")
    w("")

    # ---------------------------------------------------------------- the search and the model set
    w("## How the search was run")
    w("")
    w(report.search_note)
    w("")
    if report.candidate_variants:
        w(f"**Evidence-consistent biologies carried through:** "
          + ", ".join(f"`{_variant(v)}`" for v in report.candidate_variants) + ".")
        w("")
    if report.excluded_variants:
        w(f"**Excluded by the evidence:** "
          + ", ".join(f"`{_variant(v)}`" for v in report.excluded_variants)
          + ". A variant with no evidence-consistent steady state is falsified, so it is excluded "
            "rather than counted — a strategy cannot succeed over an empty set of initial states.")
        w("")
    if report.missing_relationships:
        w("**Missing relationships (the compiler failed closed rather than composing across them):**")
        for item in report.missing_relationships:
            w(f"- `{item}`")
        w("")
    if report.blocking_relationships:
        w(f"**Blocking:** " + ", ".join(f"`{b}`" for b in report.blocking_relationships) + ".")
        w("")
    if report.irrelevant_unknowns:
        w(f"**Unknowns that change no verdict here:** "
          + ", ".join(f"`{u}`" for u in report.irrelevant_unknowns)
          + ". Reporting these as blockers would hide the real ones in noise.")
        w("")
    if report.unobservable_states:
        w("**Not measured by the default observation model:**")
        for item in report.unobservable_states:
            w(f"- {item}")
        w("")
    if report.known_omissions:
        w("**Known omissions of the state model:**")
        for item in report.known_omissions:
            w(f"- {item}")
        w("")
    if report.assumptions:
        w("**Assumptions carried from the control problem:**")
        for item in report.assumptions:
            w(f"- *{item.epistemic_type.value}* — {item.source}"
              + (f" ({item.rationale})" if item.rationale else ""))
        w("")

    w("## What this is not")
    w("")
    w(report.no_treatment_recommendation)
    w("")
    w("Every architecture above is a statement of the form: *if these transformations were "
      "achievable and this model is right, the system would enter the target region.* The first "
      "condition is unmet for every component listed, and the second is a target definition no "
      "accountable scientist has yet approved."
      if report.target_accountability != "APPROVED" else
      "Every architecture above is conditional on its declared transformations being achievable.")
    w("")
    return "\n".join(L) + "\n"
