"""Render the capability gap reports. Generated, never edited."""
from __future__ import annotations

from rarepipe.stages.control.discovery.compiler import DiscoveryReport
from rarepipe.stages.control.discovery.kinds import GapResult


def render(report: DiscoveryReport) -> str:
    L: list[str] = []
    w = L.append
    w(f"# Capability gap reports — {report.case_ref}")
    w("")
    w("> **Agents discover possibilities. Evidence establishes claims. Deterministic code decides "
      "whether a capability exists.** Every verdict below was computed from sources a provider "
      "actually returned. This is a simulated analysis: not a finding about the patient, not a "
      "claim that anything here can be built, and not a treatment recommendation.")
    w("")
    w(f"Generated by `{report.discovery_compiler_version}` on "
      f"`{report.realization_compiler_version}` · discovery model "
      f"`{report.discovery_model_version}` · digest `{report.content_digest}`")
    w("")

    w("## The metric")
    w("")
    w("Not papers found, not candidates generated, not capabilities stored: **previously-open "
      "functional interfaces whose epistemic state changed.**")
    w("")
    if report.interfaces_whose_state_changed:
        for item in report.interfaces_whose_state_changed:
            w(f"- {item}")
    else:
        w("- none; every gap ends where it began, and each says why")
    w("")
    w(f"**Capabilities grounded:** {len(report.grounded_capabilities)}.")
    if report.abstention_reason:
        w("")
        w(f"{report.abstention_reason[0].upper()}{report.abstention_reason[1:]}.")
    w("")

    for gap in report.gaps:
        w(f"## `{gap.gap_id}`")
        w("")
        w(f"**Required:** `{gap.required_transformation}`"
          + (f", without depending on {', '.join(f'`{d}`' for d in gap.forbidden_dependencies)}"
             if gap.forbidden_dependencies else ""))
        w("")
        w(f"**Result: `{gap.result.value}`** — {gap.result_meaning}.")
        w("")
        w(f"**Why.** {gap.reason[0].upper()}{gap.reason[1:]}.")
        w("")
        w(f"**Epistemic burden:** `{gap.epistemic_burden}`. The better established the mechanism "
          "being substituted, the higher the evidence bar a candidate has to clear.")
        w("")
        if gap.current_known_paths:
            w("**What the inventory already held:**")
            for item in gap.current_known_paths:
                w(f"- {item}")
            w("")
        w("**Universe inspected.** A negative result is a statement about this, not about biology.")
        w("")
        w("| Provider | Corpus | Size | Hits |")
        w("|---|---|---|---|")
        for item in gap.universe_inspected:
            w(f"| `{item['provider']}` | {item['corpus']} | {item['corpus_size']} | "
              f"{item['hits']} |")
        w("")
        for item in gap.universe_inspected:
            if item["note"]:
                w(f"- `{item['provider']}`: {item['note']}")
        w("")
        if gap.candidate_mechanisms_considered:
            w("**Mechanism classes and candidates considered:**")
            for item in gap.candidate_mechanisms_considered:
                w(f"- {item}")
            w("")
        if gap.assessments:
            w("**Candidates, and what each validator found:**")
            w("")
            for assessment in gap.assessments:
                w(f"- `{assessment.candidate_id}` → **{assessment.entitlement.value}**")
                w(f"    - verification reached: "
                  f"{', '.join(v.value for v in assessment.verification) or 'none'}")
                w(f"    - causal depth {assessment.causal_depth}; sources "
                  f"{list(assessment.source_ids)}; references "
                  f"{list(assessment.references) or ['none in corpus']}")
                for check in assessment.checks:
                    mark = "pass" if check.passed else "**fail**"
                    w(f"    - `{check.validator}` {mark}: {check.detail}")
                if assessment.forbidden_hits:
                    w(f"    - **forbidden dependency reached:** {list(assessment.forbidden_hits)}; "
                      f"full ancestry of the output under this mechanism: "
                      f"{list(assessment.ancestry)}")
                if assessment.unsupported_intermediates:
                    w(f"    - unsupported intermediates: "
                      f"{list(assessment.unsupported_intermediates)}")
                w(f"    - {assessment.reason}")
            w("")
        if gap.grounded_capabilities:
            w("**Capabilities the builder produced:**")
            for capability in gap.grounded_capabilities:
                w(f"- `{capability.capability_id}` — {capability.input} → {capability.output} "
                  f"({capability.direction.value}), entitlement "
                  f"`{capability.entitlement.value}`, support "
                  f"`{capability.support_level.value}`, causal depth {capability.causal_depth}")
                w(f"    - validity domain: {capability.validity_domain}")
                for caveat in capability.known_caveats:
                    w(f"    - caveat: {caveat}")
            w("")
        if gap.remaining_missing_steps:
            w("**Remaining missing steps:**")
            for item in gap.remaining_missing_steps:
                w(f"- {item}")
            w("")
        if gap.context_gaps:
            w("**Context gaps:**")
            for item in gap.context_gaps:
                w(f"- {item}")
            w("")
        w(f"**Architecture impact.** {gap.architecture_impact}")
        w("")

    w("## Recompilation")
    w("")
    w("Every grounded capability updates the registry and the realization is recompiled. The delta "
      "is the result, including when there is none.")
    w("")
    w("| Target | Before | After | Changed |")
    w("|---|---|---|---|")
    for delta in report.recompiles:
        w(f"| `{delta.target}` | `{delta.before}` | `{delta.after}` | "
          f"{'**yes**' if delta.changed else 'no'} |")
    w("")
    for delta in report.recompiles:
        w(f"- `{delta.target}`: {delta.note}")
    w("")

    w("## What this is not")
    w("")
    w(report.no_treatment_recommendation)
    w("")
    w("No result here means a capability does not exist in biology. Each gap names the providers "
      "searched and the size of their corpora, because a negative result from a fifteen-claim "
      "corpus and a negative result from a literature index are different statements and must not "
      "read the same.")
    w("")
    return "\n".join(L) + "\n"
