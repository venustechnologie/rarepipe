"""Render a compilation report as a control map a scientist can read. Generated, never edited."""
from __future__ import annotations

from rarepipe.stages.control.compiler import ControlCompilationReport


def _route(steps) -> str:
    return " → ".join("+".join(step) for step in steps)


def _variant(vid: str) -> str:
    return vid.split("::", 1)[-1]


def render(report: ControlCompilationReport) -> str:
    L: list[str] = []
    w = L.append
    w(f"# Control map — {report.case_ref}")
    w("")
    w("> **Reason with agents. Prove with code.** This map was produced by the deterministic "
      "compiler. It is a simulated analysis of a state-control problem, not a finding about the "
      "patient and not a treatment recommendation.")
    w("")
    w(f"Generated by `{report.compiler_version}` · state model `{report.state_model_version}` · "
      f"rules `{report.rule_version}` · digest `{report.content_digest}`")
    w("")
    w(f"## Result: `{report.result.value}`")
    w("")
    w(report.result_meaning[0].upper() + report.result_meaning[1:] + ".")
    if report.abstention_reason:
        w("")
        w(f"Why no solution is claimed: {report.abstention_reason}.")
    if report.secondary_results:
        w("")
        w("Also true: " + ", ".join(f"`{r.value}`" for r in report.secondary_results) + ".")
    w("")
    w(f"Target accountability: **{report.target_accountability}**.")
    w("")
    w("## What counts as success")
    w("")
    w("A region of functional checkpoint behaviour — not a mechanism. Normal BubR1 abundance is "
      "deliberately not part of it.")
    w("")
    w("| Constraint | Requires | Approval |")
    w("|---|---|---|")
    for t in report.target_region:
        req = t["requires"]
        w(f"| {t['meaning']} | `{req['variable']} ∈ {list(req['allowed'])}` | {t['approval']} |")
    w("")
    w("## What is forbidden")
    w("")
    w("A trajectory that enters any of these is rejected, whatever else improves. Safety is a hard "
      "constraint, never a term traded against benefit.")
    w("")
    w("| Constraint | Unsafe when | Approval |")
    w("|---|---|---|")
    for s in report.unsafe_region:
        u = s["unsafe_when"]
        w(f"| {s['meaning']} | `{u['variable']} ∈ {list(u['allowed'])}` | {s['approval']} |")
    w("")
    w("## What could be controlled")
    w("")
    w("Biological transformations, not interventions.")
    w("")
    for c in report.candidate_controls:
        w(f"- **{c['control']}** — holds `{c['holds']}` ({c['route_class']}). {c['interpretation']}. "
          f"Feasibility: **{c['feasibility']}**; evidence type {c['epistemic_type']}.")
    w("")
    w("## Which routes exist")
    w("")
    w("Evaluated under every biology consistent with the evidence:")
    w("")
    for v in report.candidate_models:
        w(f"- `{_variant(v)}`")
    for e in report.excluded_models:
        w(f"- ~~`{_variant(e.variant_id)}`~~ — excluded: {e.reason}")
    w("")
    w("| Route | Reaches the target under | Blocked by |")
    w("|---|---|---|")
    for s in report.control_strategy_candidates:
        a = s.assessment
        works = ", ".join(f"`{_variant(v)}`" for v in a.works_in) or "none"
        blocks = ", ".join(f"`{b}`" for b in (*a.blocking_relationships, *a.feasibility_blockers)) or "nothing"
        w(f"| {_route(a.strategy)} | {works} | {blocks} |")
    if report.unsafe_trajectories_rejected:
        w("")
        w("Rejected because they pass through a forbidden state:")
        for r in report.unsafe_trajectories_rejected:
            w(f"- {_route(r['strategy'])} under `{_variant(r['variant'])}` violates {r['violates']}")
    w("")
    causal = [b for b in report.blocking_relationships if not b.startswith("control_feasibility:")]
    feasibility = [b for b in report.blocking_relationships if b.startswith("control_feasibility:")]
    w("## Which causal functions are missing")
    w("")
    for b in causal or ["none"]:
        w(f"- `{b}`")
    if feasibility:
        w("")
        w("## Which controls have unassessed feasibility")
        w("")
        w("Not causal unknowns: whether the biological transformation can be achieved at all.")
        w("")
        for b in feasibility:
            w(f"- `{b.split(':', 1)[1]}`")
    if report.irrelevant_unknowns:
        w("")
        w("Unknown but irrelevant to this question: " +
          ", ".join(f"`{u}`" for u in report.irrelevant_unknowns))
    w("")
    w("## Which measurements would change controllability")
    w("")
    w("Chosen because their outcome differs between the possibilities, not because they are "
      "interesting assays. No probability was invented to rank them.")
    w("")
    w("| Resolves | Hold | Measure | If the route works | If it fails | Valid only with | Measured by |")
    w("|---|---|---|---|---|---|---|")
    for m in report.required_measurements:
        by = ", ".join(m.observed_by) or "*latent — no experiment measures it directly*"
        alongside = ", ".join(f"`{c}`" for c in m.confounded_by) or "—"
        w(f"| `{m.resolves}` | {'+'.join(m.controls_held)} | `{m.variable}` | "
          f"{', '.join(m.values_if_route_works)} | {', '.join(m.values_if_route_fails)} | "
          f"{alongside} | {by} |")
    w("")
    w("## What each existing experiment contributes")
    w("")
    for c in report.experiment_contributions:
        w(f"### {c.experiment_id}")
        w("")
        w(c.interpretation[0].upper() + c.interpretation[1:] + ".")
        w("")
        w(f"- Resolves: {', '.join(f'`{r}`' for r in c.resolves) or 'nothing currently blocking'}")
        if c.conditional_on:
            w(f"- Conditional on {c.conditional_on}")
        gaps = (*c.observability.unobserved_target_variables, *c.observability.unobserved_safety_variables)
        w(f"- Target and safety directly measured: {'yes' if not gaps else 'no — missing ' + str(list(gaps))}")
        if c.fails_closed:
            w(f"- **Fails closed:** {c.fail_closed_reason}. The software does not choose; the "
              "options for the scientific lead are:")
            for option in c.options_for_the_scientific_lead:
                w(f"  - {option}")
        w("")
    w("## Possible actuator classes")
    w("")
    w("Consulted only because a route exists under at least one biology. Classes and their evidence "
      "only — **nothing here is recommended**, and none has been assessed for feasibility.")
    w("")
    for mapping in report.possible_actuator_classes:
        w(f"**{mapping.control_id}**")
        w("")
        for a in mapping.candidates:
            w(f"- {a.actuator_class.value}: {a.description}. Evidence: {a.evidence}.")
        w("")
    w("## Models considered for import")
    w("")
    for a in report.model_admissions:
        w(f"- `{a.model_id}`: {'admitted' if a.admitted else 'refused'} — {a.reason}")
    w("")
    w("## Assumptions and known omissions")
    w("")
    for a in report.assumptions:
        w(f"- Assumption ({a.source}): {a.rationale}")
    for o in report.known_omissions:
        w(f"- Omission: {o}")
    w("")
    return "\n".join(L) + "\n"
