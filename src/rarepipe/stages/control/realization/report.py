"""Render a realization report as a physical-realization map. Generated, never edited."""
from __future__ import annotations

from rarepipe.stages.control.realization.compiler import FunctionOutcome, RealizationReport
from rarepipe.stages.control.realization.kinds import RealizationResult


def _tree(outcome: FunctionOutcome, lines: list[str], depth: int = 0) -> None:
    pad = "    " * depth
    lines.append(f"{pad}- **`{outcome.function}`** — `{outcome.status.value}`")
    lines.append(f"{pad}  - **Burden:** `{outcome.burden.value}` — {outcome.burden_from}")
    lines.append(f"{pad}  - **Why:** {outcome.reason}")
    if outcome.missing_capability:
        lines.append(f"{pad}  - **Missing:** {outcome.missing_capability}")
    for assessment in outcome.realizations:
        lines.append(f"{pad}  - candidate `{assessment.realization_id}` → "
                     f"`{assessment.status.value}`")
        for step in assessment.steps:
            through = f" through `{step.acts_on}`" if step.acts_on else " applied directly"
            lines.append(f"{pad}      - `{step.step_id}` `{step.primitive}`"
                         f".`{step.capability_id}`{through} → {step.effect.value} "
                         f"`{step.affects}`: **{step.entitlement.value}**"
                         f"{' (grounded)' if step.grounded else ''}")
            for entitling in step.entitlings:
                lines.append(f"{pad}          - `{entitling.edge_id}` "
                             f"({entitling.ref or 'no citation'}, "
                             f"{entitling.support.value}"
                             f"{'' if entitling.verified else ', unverified'}): {entitling.reason}")
            if not step.entitlings:
                lines.append(f"{pad}          - {step.reason}")
        for missing in assessment.missing_links:
            lines.append(f"{pad}      - missing link: {missing}")
        for finding in assessment.findings:
            lines.append(f"{pad}      - {finding.kind}: {finding.detail}")
        for gap in assessment.transfer_gaps:
            lines.append(f"{pad}      - transfer gap: {gap}")
    for child in outcome.children:
        lines.append(f"{pad}  - reduces to:")
        _tree(child, lines, depth + 2)


def render(report: RealizationReport) -> str:
    L: list[str] = []
    w = L.append
    w(f"# Physical realization — {report.case_ref} · `{report.target_architecture}`")
    w("")
    w("> **Reason with agents. Prove with code.** Every entitlement below was computed from "
      "evidence the repository already holds, never from what a component asserts about itself. "
      "This is a simulated analysis: not a finding about the patient, not a claim that anything "
      "here can be built, and not a treatment recommendation.")
    w("")
    w(f"Generated by `{report.realization_compiler_version}` on "
      f"`{report.synthesis_compiler_version}` · realization model "
      f"`{report.realization_model_version}` · state model `{report.state_model_version}` · "
      f"digest `{report.content_digest}`")
    w("")
    w(f"## Result: `{report.result.value}`")
    w("")
    w(report.result_meaning[0].upper() + report.result_meaning[1:] + ".")
    if report.abstention_reason:
        w("")
        w(f"**Why not more than that.** {report.abstention_reason[0].upper()}"
          f"{report.abstention_reason[1:]}.")
    w("")
    w(f"**Logically sufficient:** {'yes' if report.logically_sufficient else 'no'} "
      f"(`{report.logical_status}`). "
      + ("The architecture reaches the state target in the mathematics; whether it can be built is "
         "the separate question this report answers."
         if report.logically_sufficient else
         "This architecture does not reach the state target under every evidence-compatible model, "
         "so a physical chain for it would inherit that limitation."))
    w("")
    w(f"**Required system:** {report.required_system}. Transfer gaps below are measured against "
      "this and are never excused by the mechanism being real somewhere else.")
    w("")
    w(f"**Evidence available:** {report.evidence_inventory_size} claims, derived from the case's "
      "own causal chain. A capability may only cite one of them, so a citation nobody made has "
      "nothing to resolve against.")
    w("")

    w("## Required transformations")
    w("")
    w("Each is the function the architecture needs, the burden it carries from what it proposes to "
      "replace, and how far it got towards real components.")
    w("")
    tree: list[str] = []
    for outcome in report.functions:
        _tree(outcome, tree)
        tree.append("")
    L.extend(tree)

    if report.missing_capabilities:
        w("## Missing capability")
        w("")
        w("What would have to exist for this to go further. This is the output worth having when "
          "the answer is not yes.")
        w("")
        for item in report.missing_capabilities:
            w(f"- {item}")
        w("")

    if report.conflicts:
        w("## Conflicts and unmet requirements")
        w("")
        for item in report.conflicts:
            w(f"- {item}")
        w("")

    if report.safety_dependencies:
        w("## Safety dependencies")
        w("")
        for item in report.safety_dependencies:
            w(f"- {item}")
        w("")

    if report.transfer_gaps:
        w("## Transfer gaps")
        w("")
        w(f"Claims entitled where they were measured, and not measured in {report.required_system}. "
          "These are why an experiment exists, not failures of the mechanism.")
        w("")
        for item in report.transfer_gaps:
            w(f"- {item}")
        w("")

    w("## Physical primitives declared")
    w("")
    w("What each piece can do, under what conditions. The important information is never that this "
      "is a named compound; it is which change it can make and what claim entitles saying so.")
    w("")
    w("| Primitive | Class | Capabilities | Cell type | Can it be built |")
    w("|---|---|---|---|---|")
    for item in report.primitives_declared:
        w(f"| `{item['primitive']}` | {item['class']} | {'; '.join(item['capabilities'])} | "
          f"{item['cell_type']} | {item['feasibility']} |")
    w("")
    for item in report.primitives_declared:
        w(f"- **`{item['primitive']}`** — {item['identity']}. *Evidence:* {item['evidence']}. "
          f"*Uncertainty:* {item['uncertainty']}. *Epistemic type:* `{item['epistemic_type']}`.")
    w("")

    if report.evidence_edges_used:
        w("## Claims this report leaned on")
        w("")
        for item in report.evidence_edges_used:
            w(f"- `{item}`")
        w("")

    w("## What this is not")
    w("")
    w(report.no_treatment_recommendation)
    w("")
    return "\n".join(L) + "\n"
